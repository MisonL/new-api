func SetupApiRequestHeader(info *common.RelayInfo, c *gin.Context, req *http.Header) {
	if info.RelayMode == relayconstant.RelayModeAudioTranscription || info.RelayMode == relayconstant.RelayModeAudioTranslation {
		// multipart/form-data
	} else if info.RelayMode == relayconstant.RelayModeRealtime {
		// websocket
	} else {
		req.Set("Content-Type", c.Request.Header.Get("Content-Type"))
		req.Set("Accept", c.Request.Header.Get("Accept"))
		if info.IsStream && c.Request.Header.Get("Accept") == "" {
			req.Set("Accept", "text/event-stream")
		}
	}
}

const clientHeaderPlaceholderPrefix = "{client_header:"

const (
	headerPassthroughAllKey        = "*"
	headerPassthroughRegexPrefix   = "re:"
	headerPassthroughRegexPrefixV2 = "regex:"
)

var passthroughSkipHeaderNamesLower = map[string]struct{}{
	// RFC 7230 hop-by-hop headers.
	"connection":          {},
	"keep-alive":          {},
	"proxy-authenticate":  {},
	"proxy-authorization": {},
	"te":                  {},
	"trailer":             {},
	"transfer-encoding":   {},
	"upgrade":             {},

	// Additional headers that should not be forwarded by name-matching passthrough rules.
	"host":            {},
	"content-length":  {},
	"accept-encoding": {},

	// WebSocket handshake headers are generated by the client/dialer.
	"sec-websocket-key":        {},
	"sec-websocket-version":    {},
	"sec-websocket-extensions": {},
}

var headerPassthroughRegexCache sync.Map // map[string]*regexp.Regexp

func getHeaderPassthroughRegex(pattern string) (*regexp.Regexp, error) {
	pattern = strings.TrimSpace(pattern)
	if pattern == "" {
		return nil, errors.New("empty regex pattern")
	}
	if v, ok := headerPassthroughRegexCache.Load(pattern); ok {
		if re, ok := v.(*regexp.Regexp); ok {
			return re, nil
		}
		headerPassthroughRegexCache.Delete(pattern)
	}
	compiled, err := regexp.Compile(pattern)
	if err != nil {
		return nil, err
	}
	actual, _ := headerPassthroughRegexCache.LoadOrStore(pattern, compiled)
	if re, ok := actual.(*regexp.Regexp); ok {
		return re, nil
	}
	return compiled, nil
}

func IsHeaderPassthroughRuleKey(key string) bool {
	return isHeaderPassthroughRuleKey(key)
}
func isHeaderPassthroughRuleKey(key string) bool {
	key = strings.TrimSpace(key)
	if key == "" {
		return false
	}
	if key == headerPassthroughAllKey {
		return true
	}
	lower := strings.ToLower(key)
	return strings.HasPrefix(lower, headerPassthroughRegexPrefix) || strings.HasPrefix(lower, headerPassthroughRegexPrefixV2)
}

func shouldSkipPassthroughHeader(name string) bool {
	name = strings.TrimSpace(name)
	if name == "" {
		return true
	}
	lower := strings.ToLower(name)
	if _, ok := passthroughSkipHeaderNamesLower[lower]; ok {
		return true
	}
	// Credentials (authorization, api-key, x-api-key, x-goog-api-key, cookie)
	// are shared with the param_override pass_headers rule so neither list can
	// grow without the other.
	return common.IsCredentialHeader(lower)
}

func applyHeaderOverridePlaceholders(template string, c *gin.Context, apiKey string) (string, bool, error) {
	trimmed := strings.TrimSpace(template)
	if strings.HasPrefix(trimmed, clientHeaderPlaceholderPrefix) {
		afterPrefix := trimmed[len(clientHeaderPlaceholderPrefix):]
		end := strings.Index(afterPrefix, "}")
		if end < 0 || end != len(afterPrefix)-1 {
			return "", false, fmt.Errorf("client_header placeholder must be the full value: %q", template)
		}

		name := strings.TrimSpace(afterPrefix[:end])
		if name == "" {
			return "", false, fmt.Errorf("client_header placeholder name is empty: %q", template)
		}
		// A credential header belongs to the caller; resolving it here would
		// hand the caller's own key to a third-party upstream, which is what the
		// wildcard passthrough rule and copy_header already refuse to do.
		if common.IsCredentialHeader(name) {
			return "", false, fmt.Errorf("client_header placeholder must not read credential header: %s", name)
		}
		if c == nil || c.Request == nil {
			return "", false, fmt.Errorf("missing request context for client_header placeholder")
		}
		clientHeaderValue := c.Request.Header.Get(name)
		if strings.TrimSpace(clientHeaderValue) == "" {
			return "", false, nil
		}
		// Do not interpolate {api_key} inside client-supplied content.
		return clientHeaderValue, true, nil
	}

	if strings.Contains(template, "{api_key}") {
		template = strings.ReplaceAll(template, "{api_key}", apiKey)
	}
	if strings.TrimSpace(template) == "" {
		return "", false, nil
	}
	return template, true, nil
}

// processHeaderOverride applies channel header overrides, with placeholder substitution.
// Supported placeholders:
//   - {api_key}: resolved to the channel API key
//   - {client_header:<name>}: resolved to the incoming request header value
//
// Header passthrough rules (keys only; values are ignored):
//   - "*": passthrough all incoming headers by name (excluding unsafe headers)
//   - "re:<regex>" / "regex:<regex>": passthrough headers whose names match the regex (Go regexp)
//
// Passthrough rules are applied first, then normal overrides are applied, so explicit overrides win.
func processHeaderOverride(info *common.RelayInfo, c *gin.Context) (map[string]string, error) {
	headerOverride := make(map[string]string)
	if info == nil {
		return headerOverride, nil
	}

	headerOverrideSource, err := common.GetEffectiveHeaderOverrideWithError(info)
	if err != nil {
		return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
	}
	profileHeaders, profileID, err := resolveHeaderProfileStrategyHeaders(c, info)
	if err != nil {
		return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
	}
	staticCodexDynamicHeaderKeys, err := validateCodexProfileStaticHeaders(profileID, profileHeaders)
	if len(staticCodexDynamicHeaderKeys) > 0 {
		recordCodexDynamicHeaderAudit(c, codexDynamicHeadersStatusRejected, staticCodexDynamicHeaderKeys)
	}
	if err != nil {
		return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
	}
	for key, value := range profileHeaders {
		trimmedKey := strings.TrimSpace(strings.ToLower(key))
		if trimmedKey == "" || shouldSkipPassthroughHeader(trimmedKey) {
			continue
		}
		if strings.TrimSpace(value) == "" {
			continue
		}
		headerOverride[trimmedKey] = value
	}
	if profileID != "" {
		logger.LogInfo(c, fmt.Sprintf("header profile applied: %s", profileID))
		mergeHeaderProfileAudit(c, info, profileID, collectHeaderOverrideKeys(headerOverride))
	}

	passAll := false
	var passthroughRegex []*regexp.Regexp
	if !info.IsChannelTest {
		for k := range headerOverrideSource {
			rawKey := strings.TrimSpace(k)
			key := strings.ToLower(rawKey)
			if rawKey == "" {
				continue
			}
			if key == headerPassthroughAllKey {
				passAll = true
				continue
			}

			var pattern string
			switch {
			case strings.HasPrefix(key, headerPassthroughRegexPrefix):
				pattern = strings.TrimSpace(rawKey[len(headerPassthroughRegexPrefix):])
			case strings.HasPrefix(key, headerPassthroughRegexPrefixV2):
				pattern = strings.TrimSpace(rawKey[len(headerPassthroughRegexPrefixV2):])
			default:
				continue
			}

			if pattern == "" {
				return nil, types.NewError(fmt.Errorf("header passthrough regex pattern is empty: %q", k), types.ErrorCodeChannelHeaderOverrideInvalid)
			}
			compiled, err := getHeaderPassthroughRegex(pattern)
			if err != nil {
				return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
			}
			passthroughRegex = append(passthroughRegex, compiled)
		}
	}

	if passAll || len(passthroughRegex) > 0 {
		if c == nil || c.Request == nil {
			return nil, types.NewError(fmt.Errorf("missing request context for header passthrough"), types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		for name := range c.Request.Header {
			if shouldSkipPassthroughHeader(name) {
				continue
			}
			if !passAll {
				matched := false
				normalizedName := strings.ToLower(strings.TrimSpace(name))
				for _, re := range passthroughRegex {
					if re.MatchString(name) || re.MatchString(normalizedName) {
						matched = true
						break
					}
				}
				if !matched {
					continue
				}
			}
			value := strings.TrimSpace(c.Request.Header.Get(name))
			if value == "" {
				continue
			}
			headerOverride[strings.ToLower(strings.TrimSpace(name))] = value
		}
	}

	for k, v := range headerOverrideSource {
		if isHeaderPassthroughRuleKey(k) {
			continue
		}
		key := strings.TrimSpace(strings.ToLower(k))
		if key == "" {
			continue
		}

		str, ok := v.(string)
		if !ok {
			return nil, types.NewError(nil, types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		if info.IsChannelTest && strings.HasPrefix(strings.TrimSpace(str), clientHeaderPlaceholderPrefix) {
			continue
		}

		value, include, err := applyHeaderOverridePlaceholders(str, c, info.ApiKey)
		if err != nil {
			return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
		}
		if !include {
			continue
		}

		headerOverride[key] = value
	}
	codexDynamicHeaderStatus, codexDynamicHeaderKeys, err := validateCodexProfileRuntimeHeaders(profileID, info, c, headerOverride)
	recordCodexDynamicHeaderAudit(c, codexDynamicHeaderStatus, codexDynamicHeaderKeys)
	if err != nil {
		return nil, types.NewError(err, types.ErrorCodeChannelHeaderOverrideInvalid)
	}
	mergeFinalHeaderOverrideAudit(c, headerOverride, getHeaderOverrideUserAgent(headerOverride))
	return headerOverride, nil
}

func isCodexHeaderProfileID(profileID string) bool {
	baseProfileID, _, _ := strings.Cut(strings.TrimSpace(profileID), "@")
	switch strings.TrimSpace(baseProfileID) {
	case "codex-cli", "codex-desktop":
		return true
	default:
		return false
	}
}

func validateCodexProfileStaticHeaders(profileID string, profileHeaders map[string]string) ([]string, error) {
	if !isCodexHeaderProfileID(profileID) {
		return nil, nil
	}
	dynamicHeaderNames := collectCodexDynamicHeaderNames(profileHeaders)
	if len(dynamicHeaderNames) > 0 {
		return dynamicHeaderNames, fmt.Errorf("header_profile_strategy Codex Profile 不能预设动态请求头，必须通过 param_override pass_headers 透传真实客户端值: %s", strings.Join(dynamicHeaderNames, ", "))
	}
	return nil, nil
}

const (
	codexDynamicHeadersStatusAbsent   = "absent"
	codexDynamicHeadersStatusPassed   = "passed"
	codexDynamicHeadersStatusRejected = "rejected"
)

func validateCodexProfileRuntimeHeaders(profileID string, info *common.RelayInfo, c *gin.Context, headers map[string]string) (string, []string, error) {
	if !isCodexHeaderProfileID(profileID) {
		return "", nil, nil
	}
	if info == nil || c == nil || c.Request == nil {
		return codexDynamicHeadersStatusRejected, nil, fmt.Errorf("header_profile_strategy Codex Profile 缺少请求上下文，无法验证 x-codex-* 请求头透传")
	}

	requestDynamicHeaders := collectCodexDynamicHTTPHeaders(c.Request.Header)
	outboundDynamicHeaders := collectCodexDynamicRequestHeaders(headers)
	dynamicHeaderNames := make([]string, 0, len(requestDynamicHeaders)+len(outboundDynamicHeaders))
	seenHeaderNames := make(map[string]struct{}, len(requestDynamicHeaders)+len(outboundDynamicHeaders))
	for headerName := range requestDynamicHeaders {
		seenHeaderNames[headerName] = struct{}{}
		dynamicHeaderNames = append(dynamicHeaderNames, headerName)
	}
	for headerName := range outboundDynamicHeaders {
		if _, exists := seenHeaderNames[headerName]; exists {
			continue
		}
		seenHeaderNames[headerName] = struct{}{}
		dynamicHeaderNames = append(dynamicHeaderNames, headerName)
	}
	if len(dynamicHeaderNames) == 0 {
		return codexDynamicHeadersStatusAbsent, nil, nil
	}
	sort.Strings(dynamicHeaderNames)
	for _, headerName := range sortedHeaderNames(requestDynamicHeaders) {
		requestValue, requested := requestDynamicHeaders[headerName]
		passedValue, passed := getHeaderValueByNormalizedName(info.RuntimePassedRequestHeaders, headerName)
		outboundValue, outbound := getHeaderValueByNormalizedName(headers, headerName)
		if !requested || !passed || passedValue != requestValue || !outbound || outboundValue != requestValue {
			return codexDynamicHeadersStatusRejected, dynamicHeaderNames, fmt.Errorf("header_profile_strategy Codex Profile 未透传真实客户端请求头: %s", headerName)
		}
	}
	for _, headerName := range sortedHeaderNames(outboundDynamicHeaders) {
		if _, requested := requestDynamicHeaders[headerName]; requested {
			continue
		}
		derivedValue, derived := getHeaderValueByNormalizedName(info.RuntimePassedRequestHeaders, headerName)
		outboundValue, outbound := getHeaderValueByNormalizedName(headers, headerName)
		if !derived || !outbound || derivedValue != outboundValue {
			return codexDynamicHeadersStatusRejected, dynamicHeaderNames, fmt.Errorf("header_profile_strategy Codex Profile 动态请求头不是客户端透传或受信任派生值: %s", headerName)
		}
	}
	return codexDynamicHeadersStatusPassed, dynamicHeaderNames, nil
}

func collectCodexDynamicRequestHeaders(headers map[string]string) map[string]string {
	if len(headers) == 0 {
		return nil
	}
	dynamicHeaders := make(map[string]string)
	for headerName, value := range headers {
		normalizedName := strings.ToLower(strings.TrimSpace(headerName))
		normalizedValue := strings.TrimSpace(value)
		if !operation_setting.IsCodexDynamicRequestHeader(normalizedName) || normalizedValue == "" {
			continue
		}
		dynamicHeaders[normalizedName] = normalizedValue
	}
	if len(dynamicHeaders) == 0 {
		return nil
	}
	return dynamicHeaders
}

func collectCodexDynamicHTTPHeaders(headers http.Header) map[string]string {
	if len(headers) == 0 {
		return nil
	}
	requestHeaders := make(map[string]string, len(headers))
	for headerName, values := range headers {
		value := headers.Get(headerName)
		if strings.TrimSpace(value) == "" && len(values) > 0 {
			// http.Header normally canonicalizes keys, but middleware and test
			// transports can construct maps with lower-case names directly.
			value = values[0]
		}
		requestHeaders[headerName] = value
	}
	return collectCodexDynamicRequestHeaders(requestHeaders)
}

func collectCodexDynamicHeaderNames(headers map[string]string) []string {
	dynamicHeaders := collectCodexDynamicRequestHeaders(headers)
	if len(dynamicHeaders) == 0 {
		return nil
	}
	return sortedHeaderNames(dynamicHeaders)
}

func sortedHeaderNames(headers map[string]string) []string {
	names := make([]string, 0, len(headers))
	for name := range headers {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func recordCodexDynamicHeaderAudit(c *gin.Context, status string, headerNames []string) {
	if c == nil || strings.TrimSpace(status) == "" {
		return
	}
	audit, _ := common2.GetContextKeyType[service.RuntimeHeaderPolicyAudit](c, rootconstant.ContextKeyChannelHeaderPolicyAudit)
	audit.CodexDynamicHeadersStatus = status
	audit.CodexDynamicHeaderKeys = mergeHeaderKeys(audit.CodexDynamicHeaderKeys, headerNames)
	common2.SetContextKey(c, rootconstant.ContextKeyChannelHeaderPolicyAudit, audit)
}

func getHeaderValueByNormalizedName(headers map[string]string, normalizedHeaderName string) (string, bool) {
	for headerName, value := range headers {
		if strings.ToLower(strings.TrimSpace(headerName)) != normalizedHeaderName {
			continue
		}
		value = strings.TrimSpace(value)
		return value, value != ""
	}
	return "", false
}

func mergeHeaderProfileAudit(c *gin.Context, info *common.RelayInfo, profileID string, headerKeys []string) {
	if c == nil || info == nil || info.ChannelMeta == nil || info.ChannelMeta.ChannelOtherSettings.HeaderProfileStrategy == nil {
		return
	}
	audit, _ := common2.GetContextKeyType[service.RuntimeHeaderPolicyAudit](c, rootconstant.ContextKeyChannelHeaderPolicyAudit)
	audit.HeaderProfileID = profileID
	audit.HeaderProfileMode = string(info.ChannelMeta.ChannelOtherSettings.HeaderProfileStrategy.Mode)
	audit.HeaderProfileApplied = true
	audit.AppliedHeaderKeys = mergeHeaderKeys(audit.AppliedHeaderKeys, headerKeys)
	common2.SetContextKey(c, rootconstant.ContextKeyChannelHeaderPolicyAudit, audit)
}

func mergeFinalHeaderOverrideAudit(c *gin.Context, headers map[string]string, appliedUserAgent string) {
	if c == nil {
		return
	}
	audit, _ := common2.GetContextKeyType[service.RuntimeHeaderPolicyAudit](c, rootconstant.ContextKeyChannelHeaderPolicyAudit)
	audit.AppliedHeaderKeys = mergeHeaderKeys(audit.AppliedHeaderKeys, collectHeaderOverrideKeys(headers))
	audit.AppliedHeaders = mergeHeaderAuditEntries(audit.AppliedHeaders, headers)
	if appliedUserAgent != "" {
		audit.AppliedUserAgent = appliedUserAgent
	}
	common2.SetContextKey(c, rootconstant.ContextKeyChannelHeaderPolicyAudit, audit)
}

func mergeDefaultUserAgentAudit(c *gin.Context, req *http.Request, resp *http.Response) {
	if c == nil || req == nil || resp == nil {
		return
	}
	if hasUserAgentHeader(req.Header) && !strings.EqualFold(strings.TrimSpace(req.Header.Get("User-Agent")), service.DefaultUserAgent) {
		return
	}
	defaultUA := defaultTransportUserAgent(resp)
	if defaultUA == "" {
		return
	}
	audit, _ := common2.GetContextKeyType[service.RuntimeHeaderPolicyAudit](c, rootconstant.ContextKeyChannelHeaderPolicyAudit)
	if strings.TrimSpace(audit.AppliedUserAgent) != "" {
		return
	}
	audit.AppliedUserAgent = defaultUA
	common2.SetContextKey(c, rootconstant.ContextKeyChannelHeaderPolicyAudit, audit)
}

func defaultTransportUserAgent(resp *http.Response) string {
	return service.DefaultUserAgent
}

func hasUserAgentHeader(headers http.Header) bool {
	for name := range headers {
		if strings.EqualFold(name, "User-Agent") {
			return true
		}
	}
	return false
}

func getHeaderOverrideUserAgent(headers map[string]string) string {
	for key, value := range headers {
		if strings.EqualFold(key, "User-Agent") {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

func collectHeaderOverrideKeys(headers map[string]string) []string {
	if len(headers) == 0 {
		return nil
	}
	keys := make([]string, 0, len(headers))
	for key := range headers {
		keys = append(keys, key)
	}
	return keys
}

func mergeHeaderKeys(existing []string, added []string) []string {
	if len(existing) == 0 && len(added) == 0 {
		return nil
	}
	seen := map[string]struct{}{}
	merged := make([]string, 0, len(existing)+len(added))
	for _, key := range append(existing, added...) {
		trimmed := strings.TrimSpace(key)
		if trimmed == "" {
			continue
		}
		lower := strings.ToLower(trimmed)
		if _, exists := seen[lower]; exists {
			continue
		}
		seen[lower] = struct{}{}
		merged = append(merged, trimmed)
	}
	return merged
}

func mergeHeaderAuditEntries(existing []service.AppliedHeaderAuditEntry, headers map[string]string) []service.AppliedHeaderAuditEntry {
	if len(existing) == 0 && len(headers) == 0 {
		return nil
	}

	values := map[string]service.AppliedHeaderAuditEntry{}
	for _, entry := range existing {
		key := strings.TrimSpace(entry.Key)
		if key == "" {
			continue
		}
		values[strings.ToLower(key)] = service.AppliedHeaderAuditEntry{
			Key:   key,
			Value: service.RedactHeaderAuditValue(key, entry.Value),
		}
	}
	for key, value := range headers {
		key = strings.TrimSpace(key)
		value = strings.TrimSpace(value)
		if key == "" || value == "" {
			continue
		}
		values[strings.ToLower(key)] = service.AppliedHeaderAuditEntry{
			Key:   key,
			Value: service.RedactHeaderAuditValue(key, value),
		}
	}

	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	merged := make([]service.AppliedHeaderAuditEntry, 0, len(keys))
	for _, key := range keys {
		merged = append(merged, values[key])
	}
	return merged
}

func resolveHeaderProfileStrategyHeaders(c *gin.Context, info *common.RelayInfo) (map[string]string, string, error) {
	if c == nil || info == nil || info.ChannelMeta == nil {
		return nil, "", nil
	}
	strategy := info.ChannelMeta.ChannelOtherSettings.HeaderProfileStrategy
	return service.ResolveChannelRuntimeHeaderProfileHeadersForRequest(c, info.ChannelMeta.ChannelId, strategy, info.RetryIndex)
}

func ResolveHeaderOverride(info *common.RelayInfo, c *gin.Context) (map[string]string, error) {
	return processHeaderOverride(info, c)
}

func applyHeaderOverrideToRequest(req *http.Request, headerOverride map[string]string) {
	if req == nil {
		return
	}
	for key, value := range headerOverride {
		req.Header.Set(key, value)
		// set Host in req
		if strings.EqualFold(key, "Host") {
			req.Host = value
		}
	}
}

func ApplyHeaderOverrideToRequest(req *http.Request, headerOverride map[string]string) {
	applyHeaderOverrideToRequest(req, headerOverride)
}

